// 解锁.js
// ==========================================
// 独立的屏幕解锁脚本
// 适用：定时任务启动前唤醒设备
// ==========================================

toastLog("🔓 正在尝试唤醒并解锁屏幕...");
sleep(2000)
// 1. 唤醒屏幕
device.wakeUp();
sleep(2000); // 给屏幕和系统 UI 一点启动时间

// 2. 检查当前是否已经解锁进入桌面
// 如果不用密码直接进桌面了，就不执行下面的上滑和输入密码
var isLocked = true;
// 这里可以用判断当前界面的特征，比如桌面通常没有“输入密码”的提示
// 考虑到咱们没有现成的锁屏判断API，用简单的找节点或者直接强制走一遍流程

var w = device.width;
var h = device.height;

// 3. 上滑呼出密码盘
// 从屏幕下方往上滑，连续滑两次确保出密码盘
swipe(w * 0.7, h * 0.8, w * 0.4, h * 0.3, 400); 
sleep(1500); 
swipe(w * 0.7, h * 0.8, w * 0.4, h * 0.3, 400); 
sleep(2000); 

// 4. 盲点输入密码（基于你的特定坐标）
toastLog("输入密码...");
click(810, 1499); sleep(800); 
click(864, 1300); sleep(800); 
click(820, 1427); sleep(800); 
click(832, 1325); sleep(2500); // 最后一次输入后，等待较长一点让系统验证并进入桌面

toastLog("✅ 解锁流程执行完毕！");
